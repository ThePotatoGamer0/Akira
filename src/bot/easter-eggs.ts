export function easterEgg(name: string, rest: string): string | null {
  if (rest.trim().length > 0) return null;
  return EASTER_EGGS[name.trim().toLowerCase()] ?? null;
}

/** Match `a` or `k` glued to an egg, including `kys` and `ass`. */
export function easterEggFromMessage(content: string, prefixes: readonly string[]): string | null {
  const trimmed = content.trim();
  if (!trimmed) return null;
  const lower = trimmed.toLowerCase();
  const ordered = [...new Set(prefixes.map((prefix) => prefix.toLowerCase()))].sort((a, b) => b.length - a.length);
  for (const prefix of ordered) {
    if (!prefix || !lower.startsWith(prefix)) continue;
    const body = trimmed.slice(prefix.length).trim();
    if (!body) continue;
    const splitAt = body.search(/\s/);
    const name = splitAt === -1 ? body : body.slice(0, splitAt);
    const rest = splitAt === -1 ? "" : body.slice(splitAt + 1).trim();
    const egg = easterEgg(name, rest);
    if (egg) return egg;
  }
  return null;
}
